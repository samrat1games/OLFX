#!/usr/bin/env python3
"""Generates OLFX/XR/olfx_vrapi_stubs.S + olfx_vrapi_names.c from the exports of the Gear VR/Quest VrApi shim
(OLFX/XRLibs/libolfx_vrapi.so). Each stub forwards to the shim's function, loaded lazily through Husk's linker."""
import struct, sys, os
root = os.path.join(os.path.dirname(__file__), '..')
d = open(os.path.join(root, 'OLFX/XRLibs/libolfx_vrapi.so'), 'rb').read()
shoff = struct.unpack_from('<Q', d, 0x28)[0]; shentsize, shnum, _ = struct.unpack_from('<HHH', d, 0x3A)
secs = [struct.unpack_from('<IIQQQQIIQQ', d, shoff + i * shentsize) for i in range(shnum)]
names = []
for (_, typ, _, _, off, size, link, _, _, _) in secs:
    if typ == 11:
        st = secs[link]
        for k in range(0, size, 24):
            n, _, _, shndx, _, _ = struct.unpack_from('<IBBHQQ', d, off + k)
            s = d[st[4] + n:d.index(b'\0', st[4] + n)].decode()
            if shndx and s.startswith('vrapi_'): names.append(s)
names = sorted(set(names))
S = ['// Generated by scripts/gen_vrapi_stubs.py: do not edit.', '.text', '.align 2']
for i, n in enumerate(names):
    S += [f'.globl _olfx_vrapi_stub_{i}', f'.align 2', f'_olfx_vrapi_stub_{i}:',
          '\tadrp x16, _olfx_vrapi_tab@PAGE', f'\tadd x16, x16, _olfx_vrapi_tab@PAGEOFF', f'\tldr x16, [x16, #{i*8}]',
          '\tcbz x16, 1f', '\tbr x16', f'1:\tmov w17, #{i}', '\tb _olfx_vrapi_slow']
S += ['.globl _olfx_vrapi_slow', '.align 2', '_olfx_vrapi_slow:',
      '\tstp x29, x30, [sp, #-16]!', '\tmov x29, sp', '\tsub sp, sp, #208',
      '\tstp x0, x1, [sp, #0]', '\tstp x2, x3, [sp, #16]', '\tstp x4, x5, [sp, #32]', '\tstp x6, x7, [sp, #48]', '\tstr x8, [sp, #64]',
      '\tstp q0, q1, [sp, #80]', '\tstp q2, q3, [sp, #112]', '\tstp q4, q5, [sp, #144]', '\tstp q6, q7, [sp, #176]',
      '\tmov w0, w17', '\tbl _olfx_vrapi_resolve', '\tmov x16, x0',
      '\tldp x0, x1, [sp, #0]', '\tldp x2, x3, [sp, #16]', '\tldp x4, x5, [sp, #32]', '\tldp x6, x7, [sp, #48]', '\tldr x8, [sp, #64]',
      '\tldp q0, q1, [sp, #80]', '\tldp q2, q3, [sp, #112]', '\tldp q4, q5, [sp, #144]', '\tldp q6, q7, [sp, #176]',
      '\tmov sp, x29', '\tldp x29, x30, [sp], #16', '\tbr x16']
open(os.path.join(root, 'OLFX/XR/olfx_vrapi_stubs.S'), 'w').write('\n'.join(S) + '\n')
C = ['// Generated by scripts/gen_vrapi_stubs.py: do not edit.', '#include <stddef.h>', '#include "olfx_vrapi.h"']
C += [f'extern void olfx_vrapi_stub_{i}(void);' for i in range(len(names))]
C += [f'const int olfx_vrapi_count = {len(names)};', 'const char *const olfx_vrapi_names[] = {'] + [f'\t"{n}",' for n in names] + ['};',
      'void *const olfx_vrapi_stubs[] = {'] + [f'\t(void *)olfx_vrapi_stub_{i},' for i in range(len(names))] + ['};']
open(os.path.join(root, 'OLFX/XR/olfx_vrapi_names.c'), 'w').write('\n'.join(C) + '\n')
print(len(names), 'exports')
