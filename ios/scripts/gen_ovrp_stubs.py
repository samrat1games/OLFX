#!/usr/bin/env python3
"""Generates OLFX/XR/olfx_ovrp_stubs.S + olfx_ovrp_names.c from the exports of the OVRPlugin (Oculus XR plugin) shim
(OLFX/XRLibs/libolfx_ovrplugin.so). Each stub forwards to the shim's function, loaded lazily through Husk's linker."""
import struct, sys, os
root = os.path.join(os.path.dirname(__file__), '..')
d = open(os.path.join(root, 'OLFX/XRLibs/libolfx_ovrplugin.so'), 'rb').read()
shoff = struct.unpack_from('<Q', d, 0x28)[0]; shentsize, shnum, _ = struct.unpack_from('<HHH', d, 0x3A)
secs = [struct.unpack_from('<IIQQQQIIQQ', d, shoff + i * shentsize) for i in range(shnum)]
names = []
for (_, typ, _, _, off, size, link, _, _, _) in secs:
    if typ == 11:
        st = secs[link]
        for k in range(0, size, 24):
            n, _, _, shndx, _, _ = struct.unpack_from('<IBBHQQ', d, off + k)
            s = d[st[4] + n:d.index(b'\0', st[4] + n)].decode()
            if shndx and s.startswith('ovrp_'): names.append(s)
names = sorted(set(names))
S = ['// Generated by scripts/gen_ovrp_stubs.py: do not edit.', '.text', '.align 2']
for i, n in enumerate(names):
    # fast path: straight into the shim; while _olfx_ovrp_trace_n > 0 every call goes through the logging path instead
    S += [f'.globl _olfx_ovrp_stub_{i}', f'.align 2', f'_olfx_ovrp_stub_{i}:']
    if n in ('ovrp_Initialize6', 'ovrp_Initialize7'):
        # the OpenGL ES VR path is an opt-in (Hand-Tracking settings): off, the game gets ovrpFailure_Unsupported and runs flat
        S += ['\tadrp x17, _olfx_ovrp_gles_on@PAGE', '\tldr w17, [x17, _olfx_ovrp_gles_on@PAGEOFF]', '\tcbnz w17, 3f',
              '\tmov w0, #-1004', '\tret', '3:']
    S += ['\tadrp x16, _olfx_ovrp_tab@PAGE', f'\tadd x16, x16, _olfx_ovrp_tab@PAGEOFF', f'\tldr x16, [x16, #{i*8}]',
          '\tcbz x16, 1f',
          '\tadrp x17, _olfx_ovrp_trace_n@PAGE', '\tldr w17, [x17, _olfx_ovrp_trace_n@PAGEOFF]', '\tcbnz w17, 2f',
          '\tbr x16', f'1:\tmov w17, #{i}', '\tb _olfx_ovrp_slow', f'2:\tmov w17, #{i}', '\tb _olfx_ovrp_traced']
def slow(label, fn):
    return [f'.globl {label}', '.align 2', f'{label}:',
      '\tstp x29, x30, [sp, #-16]!', '\tmov x29, sp', '\tsub sp, sp, #208',
      '\tstp x0, x1, [sp, #0]', '\tstp x2, x3, [sp, #16]', '\tstp x4, x5, [sp, #32]', '\tstp x6, x7, [sp, #48]', '\tstr x8, [sp, #64]',
      '\tstp q0, q1, [sp, #80]', '\tstp q2, q3, [sp, #112]', '\tstp q4, q5, [sp, #144]', '\tstp q6, q7, [sp, #176]',
      '\tmov w0, w17', f'\tbl {fn}', '\tmov x16, x0',
      '\tldp x0, x1, [sp, #0]', '\tldp x2, x3, [sp, #16]', '\tldp x4, x5, [sp, #32]', '\tldp x6, x7, [sp, #48]', '\tldr x8, [sp, #64]',
      '\tldp q0, q1, [sp, #80]', '\tldp q2, q3, [sp, #112]', '\tldp q4, q5, [sp, #144]', '\tldp q6, q7, [sp, #176]',
      '\tmov sp, x29', '\tldp x29, x30, [sp], #16', '\tbr x16']
S += slow('_olfx_ovrp_slow', '_olfx_ovrp_resolve') + slow('_olfx_ovrp_traced', '_olfx_ovrp_resolve_traced')
open(os.path.join(root, 'OLFX/XR/olfx_ovrp_stubs.S'), 'w').write('\n'.join(S) + '\n')
C = ['// Generated by scripts/gen_ovrp_stubs.py: do not edit.', '#include <stddef.h>', '#include "olfx_ovrp.h"']
C += [f'extern void olfx_ovrp_stub_{i}(void);' for i in range(len(names))]
C += [f'const int olfx_ovrp_count = {len(names)};', 'const char *const olfx_ovrp_names[] = {'] + [f'\t"{n}",' for n in names] + ['};',
      'void *const olfx_ovrp_stubs[] = {'] + [f'\t(void *)olfx_ovrp_stub_{i},' for i in range(len(names))] + ['};']
open(os.path.join(root, 'OLFX/XR/olfx_ovrp_names.c'), 'w').write('\n'.join(C) + '\n')
print(len(names), 'exports')
