#!/usr/bin/env python3
"""Generate third_party/ovrplugin-openxr-shim/shim/src/olfx_extra_stubs.c from a per-symbol policy.

Inputs
  names.h      every function exported by the real libOVRPlugin (produced by gen.py)
  shim/src/*.c the upstream + OLFX sources; any ovrp_* defined there is tier `impl` and is skipped
  policy.tsv   explicit overrides (tab separated: name, tier, note)

Tiers
  unsupported  return ovrpFailure_Unsupported (default for every symbol nobody implements)
  ok           return ovrpSuccess without touching out-parameters (only for calls whose
               signature is known and whose effect the game cannot observe)
  ret=<int>    return that exact ovrpResult

Out-parameters are never written: the stubs are declared (void) because the real signatures
are unknown, so writing through a guessed pointer could corrupt memory.

Usage
  gen_policy.py            rewrite olfx_extra_stubs.c
  gen_policy.py --check    exit 1 if the file on disk differs (used by tests/CI)
  gen_policy.py --suggest LOG   list unsupported stubs that a game actually called, from the
                                `OLFX-OVR call <name>` lines of an adb logcat capture
"""
import argparse
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SRC = HERE.parent.parent / "third_party/ovrplugin-openxr-shim/shim/src"
OUT = SRC / "olfx_extra_stubs.c"
NAME_RE = re.compile(r'"(ovrp_[A-Za-z0-9_]+)"')
# any return type (ovrpResult, ovrpBool, ...): a definition is `OVRP_EXPORT <type> ovrp_X(`
DEF_RE = re.compile(r'OVRP_EXPORT[^;{(]*?\b(ovrp_[A-Za-z0-9_]+)\s*\(')
# passthru.c defines exports through PT_STUB(Name, const) -> ovrp_Name
MACRO_RE = re.compile(r'^PT_STUB\(([A-Za-z0-9_]+)\s*,', re.M)
TIER_RE = re.compile(r'^(unsupported|ok|ret=-?\d+)$')

HEADER = """\
// SPDX-License-Identifier: MIT
// OLFX: exports observed in newer OVRPlugin builds but absent from the upstream RE4 surface.
// GENERATED by tools/ovr_shim/gen_policy.py from names.h + policy.tsv. Do not edit by hand.
// Keeps dlsym resolution complete. Default tier is `unsupported`; nothing here pretends a feature works
// unless policy.tsv says so, and no out-parameter is ever written.
#include "ovrplugin_shim.h"

"""


def load_policy(path):
    pol = {}
    for n, line in enumerate(path.read_text().splitlines(), 1):
        if not line.strip() or line.lstrip().startswith("#"):
            continue
        cols = line.split("\t")
        if len(cols) < 2 or not TIER_RE.match(cols[1].strip()):
            sys.exit(f"{path.name}:{n}: expected `name<TAB>unsupported|ok|ret=<int>[<TAB>note]`")
        pol[cols[0].strip()] = cols[1].strip()
    return pol


def render():
    names = set(NAME_RE.findall((HERE / "names.h").read_text()))
    impl = set()
    for f in SRC.glob("*.c"):
        if f.name != OUT.name:
            text = f.read_text()
            impl |= set(DEF_RE.findall(text))
            impl |= {"ovrp_" + m for m in MACRO_RE.findall(text)}
    pol = load_policy(HERE / "policy.tsv")
    unknown = sorted(set(pol) - names)
    if unknown:
        sys.exit("policy.tsv names not exported by the real OVRPlugin: " + ", ".join(unknown))
    clash = sorted(set(pol) & impl)
    if clash:
        sys.exit("policy.tsv overrides symbols that are implemented (tier impl): " + ", ".join(clash))
    body = []
    for n in sorted(names - impl):
        tier = pol.get(n, "unsupported")
        ret = {"unsupported": "ovrpFailure_Unsupported", "ok": "ovrpSuccess"}.get(tier) or tier[4:]
        body.append(f"OVRP_EXPORT ovrpResult {n}(void) {{ return {ret}; }}\n")
    return HEADER + "".join(body), len(impl & names), len(body), len(pol)


def suggest(log):
    stubs = set(DEF_RE.findall(OUT.read_text()))
    seen = {}
    for m in re.finditer(r'OLFX-OVR.*call (ovrp_\w+) \(#(\d+)\)', Path(log).read_text(errors="replace")):
        seen[m.group(1)] = m.group(2)
    hit = sorted(n for n in seen if n in stubs)
    print(f"{len(hit)} unsupported stubs were called by the game:")
    for n in hit:
        print(f"{n}\tunsupported\t# called; decide: keep, ok, or implement")


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--check", action="store_true")
    ap.add_argument("--suggest", metavar="LOG")
    a = ap.parse_args()
    if a.suggest:
        return suggest(a.suggest)
    text, n_impl, n_stub, n_pol = render()
    if a.check:
        if not OUT.exists() or OUT.read_text() != text:
            sys.exit("olfx_extra_stubs.c is stale: run tools/ovr_shim/gen_policy.py")
        return
    OUT.write_text(text)
    print(f"{n_impl} implemented, {n_stub} stubbed ({n_pol} policy overrides) -> {OUT.name}")


if __name__ == "__main__":
    main()
