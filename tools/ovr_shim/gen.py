#!/usr/bin/env python3
"""Generate stubs for a forwarding shim of libOVRPlugin.so (every exported symbol is forwarded to the real lib)."""
import struct, sys

def exports(path):
    d = open(path, 'rb').read()
    shoff = struct.unpack_from('<Q', d, 0x28)[0]
    shentsize, shnum, _ = struct.unpack_from('<HHH', d, 0x3A)
    secs = []
    for i in range(shnum):
        name, typ, flags, addr, off, size, link, info, align, entsize = struct.unpack_from('<IIQQQQIIQQ', d, shoff + i * shentsize)
        secs.append((typ, off, size, link))
    out = []
    for typ, off, size, link in secs:
        if typ == 11:
            stroff = secs[link][1]
            for k in range(size // 24):
                st_name, st_info, st_other, st_shndx, st_value, st_size = struct.unpack_from('<IBBHQQ', d, off + k * 24)
                if st_shndx == 0 or not st_name:
                    continue
                if st_info & 0xF not in (1, 2):  # OBJECT / FUNC
                    continue
                n = d[stroff + st_name:d.index(b'\0', stroff + st_name)].decode('latin1')
                out.append((n, st_info & 0xF))
    return out

syms = [n for n, t in exports(sys.argv[1]) if t == 2 and (n.startswith('ovrp_') or n.startswith('JNI_') or n.startswith('Java_'))]
syms = sorted(set(syms))
with open('stubs.S', 'w') as f:
    f.write('// generated by gen.py: one forwarding stub per exported function\n')
    f.write('.text\n')
    for i, n in enumerate(syms):
        f.write(f'.globl {n}\n.type {n}, %function\n.p2align 2\n{n}:\n')
        # save argument registers, log the call, restore, jump to the real function
        f.write('    stp x0, x1, [sp, #-80]!\n    stp x2, x3, [sp, #16]\n    stp x4, x5, [sp, #32]\n    stp x6, x7, [sp, #48]\n    str x30, [sp, #64]\n')
        f.write(f'    mov w0, #{i}\n    bl olfx_trace\n')
        f.write('    ldr x30, [sp, #64]\n    ldp x6, x7, [sp, #48]\n    ldp x4, x5, [sp, #32]\n    ldp x2, x3, [sp, #16]\n    ldp x0, x1, [sp], #80\n')
        f.write(f'    adrp x16, olfx_real_table\n    add x16, x16, :lo12:olfx_real_table\n    ldr x16, [x16, #{i * 8}]\n    br x16\n')
with open('names.h', 'w') as f:
    f.write(f'#define OLFX_COUNT {len(syms)}\nstatic const char *const olfx_names[OLFX_COUNT] = {{\n')
    for n in syms:
        f.write(f'    "{n}",\n')
    f.write('};\n')
print(len(syms), 'functions')
