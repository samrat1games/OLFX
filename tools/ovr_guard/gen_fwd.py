#!/usr/bin/env python3
"""Generate forwarding stubs for libovrplatformloader.so (arm64).

Usage: gen_fwd.py REAL_LOADER.so OUTDIR [--skip name,name,...]

Every exported function of the real loader becomes a 4-instruction trampoline that jumps to the same
symbol in libovrplatformloader_real.so (argument registers are never touched, so it works for any
signature). Functions listed in --skip are implemented by hand in guard.c and get no stub.
Outputs OUTDIR/fwd_stubs.S and OUTDIR/fwd_names.h.
"""
import struct, sys
from pathlib import Path


def exported_functions(path):
    d = Path(path).read_bytes()
    if d[:4] != b"\x7fELF" or d[4] != 2:
        sys.exit("not a 64-bit ELF")
    shoff = struct.unpack_from("<Q", d, 0x28)[0]
    shentsize, shnum, _ = struct.unpack_from("<HHH", d, 0x3A)
    secs = [struct.unpack_from("<IIQQQQIIQQ", d, shoff + i * shentsize) for i in range(shnum)]
    out = set()
    for _n, typ, _f, _a, off, size, link, _i, _al, _es in secs:
        if typ != 11:  # SHT_DYNSYM
            continue
        stroff = secs[link][4]
        for k in range(size // 24):
            st_name, st_info, _o, st_shndx, _v, _s = struct.unpack_from("<IBBHQQ", d, off + k * 24)
            if st_shndx == 0 or not st_name or (st_info & 0xF) != 2:  # defined FUNC only
                continue
            out.add(d[stroff + st_name:d.index(b"\0", stroff + st_name)].decode("latin1"))
    return sorted(out)


def main():
    if len(sys.argv) < 3:
        sys.exit(__doc__)
    skip = set()
    if "--skip" in sys.argv:
        skip = set(sys.argv[sys.argv.index("--skip") + 1].split(","))
    names = [n for n in exported_functions(sys.argv[1]) if n not in skip]
    out = Path(sys.argv[2])
    out.mkdir(parents=True, exist_ok=True)
    with open(out / "fwd_stubs.S", "w") as f:
        f.write("// generated by gen_fwd.py: one forwarding trampoline per exported function\n.text\n")
        for i, n in enumerate(names):
            f.write(f".globl {n}\n.type {n}, %function\n.p2align 2\n{n}:\n")
            # Unsupported compatibility exports return no value/payload. No original Meta loader is invoked.
            f.write("    mov x0, xzr\n    ret\n")
    with open(out / "fwd_names.h", "w") as f:
        f.write(f"#define GUARD_FWD_COUNT {len(names)}\n"
                "static const char *const guard_fwd_names[GUARD_FWD_COUNT] = {\n")
        f.writelines(f'    "{n}",\n' for n in names)
        f.write("};\n")
    print(len(names), "forwarded,", len(skip), "hand-written")


if __name__ == "__main__":
    main()
